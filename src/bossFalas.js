function sortear(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function getFalaInicio(boss, petId, historicoJogador) {
  const falas = boss === 'yorax' ? YORAX_FALAS : THALMOR_FALAS;

  // 1% de chance de fala lendária
  if (Math.random() < 0.01) return sortear(falas.lendarias);

  // Memória de rivais
  const { vitorias = 0, derrotas = 0, ultimaResultado } = historicoJogador;
  if (vitorias >= 3) return sortear(falas.memoria.venceuVarias);
  if (vitorias >= 1) return sortear(falas.memoria.venceuUmaVez);
  if (ultimaResultado === 'derrota') return sortear(falas.memoria.perdeuAntes);

  // Contextual por pet
  const ctx = falas.contextual;
  if (petId === 'lendario' && ctx.lendarioRaro && Math.random() < 0.3) return sortear(ctx.lendarioRaro);
  if (ctx[petId]) return sortear(ctx[petId]);

  // Fallback lendária
  return sortear(falas.lendarias);
}

export function getProvocacao(boss) {
  const falas = boss === 'yorax' ? YORAX_FALAS : THALMOR_FALAS;
  return sortear(falas.provocacoes);
}
